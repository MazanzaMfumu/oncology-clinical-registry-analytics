def filter_valid_quality_records(
    df: pd.DataFrame,
) -> tuple[pd.DataFrame, int]:
    """Explicitly retain only quality_status == 'valid' and document the filter."""
    normalized = normalize_text(df[QUALITY_STATUS_COL]).str.lower()
    display_values = normalized.fillna("<missing>")

    distribution = (
        display_values.value_counts(dropna=False)
        .rename_axis(QUALITY_STATUS_COL)
        .reset_index(name="n_records")
    )
    distribution["percent"] = 100 * distribution["n_records"] / len(df)
    distribution.to_csv(
        REPORT_DIR / "quality_status_distribution.csv",
        index=False,
    )

    valid_mask = normalized.eq(VALID_QUALITY_VALUE).fillna(False)
    filtered = df.loc[valid_mask].copy()
    excluded = int((~valid_mask).sum())

    pd.DataFrame(
        [
            {"metric": "source_records", "value": int(len(df))},
            {"metric": "quality_valid_records", "value": int(valid_mask.sum())},
            {
                "metric": "excluded_nonvalid_or_missing_quality_status",
                "value": excluded,
            },
            {
                "metric": "quality_filter",
                "value": f"{QUALITY_STATUS_COL} == {VALID_QUALITY_VALUE!r}",
            },
        ]
    ).to_csv(REPORT_DIR / "quality_filter_summary.csv", index=False)

    if filtered.empty:
        fail("No records remain after the explicit quality-status filter.")

    print(
        f"Quality filter: retained {len(filtered)} of {len(df)} records "
        f"where {QUALITY_STATUS_COL} == {VALID_QUALITY_VALUE!r}."
    )
    return filtered, excluded


def validate_event_indicator(df: pd.DataFrame) -> pd.DataFrame:
    """Validate event and cross-check every recognized vital-status value."""
    result = df.copy()
    original_event = result[EVENT_COL]
    numeric_event = pd.to_numeric(original_event, errors="coerce")

    invalid_nonmissing = original_event.notna() & numeric_event.isna()
    if invalid_nonmissing.any():
        examples = original_event.loc[invalid_nonmissing].astype(str).unique()[:10]
        fail(
            f"{EVENT_COL!r} contains non-numeric values: {examples.tolist()}. "
            "Only 0 and 1 are permitted."
        )

    result[EVENT_COL] = numeric_event
    nonmissing_values = set(result[EVENT_COL].dropna().unique())
    if not nonmissing_values.issubset({0, 1, 0.0, 1.0}):
        fail(
            f"{EVENT_COL!r} contains values other than 0 and 1: "
            f"{sorted(nonmissing_values)}"
        )

    vital = normalize_text(result[VITAL_STATUS_COL]).str.lower()
    mapping = {"alive": 0, "dead": 1}

    unknown_vital = vital.notna() & ~vital.isin(mapping)
    if unknown_vital.any():
        examples = result.loc[unknown_vital, VITAL_STATUS_COL].astype(str).unique()[:10]
        fail(
            f"Unrecognized values in {VITAL_STATUS_COL!r}: {examples.tolist()}. "
            "Expected only 'Alive' and 'Dead'."
        )

    expected_event = vital.map(mapping)
    comparable = expected_event.notna() & result[EVENT_COL].notna()
    inconsistent = comparable & expected_event.ne(result[EVENT_COL])
    if inconsistent.any():
        fail(
            f"Detected {int(inconsistent.sum())} inconsistencies between "
            f"{VITAL_STATUS_COL!r} and {EVENT_COL!r}."
        )

    pd.crosstab(
        result[VITAL_STATUS_COL],
        result[EVENT_COL],
        dropna=False,
    ).to_csv(REPORT_DIR / "vital_status_event_crosstab.csv")

    return result


def prepare_survival_data(
    df: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame, int]:
    """Validate core survival fields within the quality-valid cohort."""
    working = df.copy()
    working[DURATION_COL] = pd.to_numeric(
        working[DURATION_COL],
        errors="coerce",
    )
    working[EVENT_COL] = pd.to_numeric(
        working[EVENT_COL],
        errors="coerce",
    )
    working[STAGE_COL] = normalize_text(working[STAGE_COL])

    flags = pd.DataFrame(index=working.index)
    flags["missing_duration"] = working[DURATION_COL].isna()
    flags["negative_duration"] = working[DURATION_COL].lt(0).fillna(False)
    flags["missing_event"] = working[EVENT_COL].isna()
    flags["invalid_event"] = (
        working[EVENT_COL].notna()
        & ~working[EVENT_COL].isin([0, 1])
    )
    flags["missing_stage"] = (
        working[STAGE_COL].isna()
        | working[STAGE_COL].eq("")
    )
    flags["exclude_from_core_survival"] = flags.any(axis=1)

    report = pd.DataFrame(
        {
            "criterion": flags.columns,
            "n_records": [
                int(flags[column].sum())
                for column in flags.columns
            ],
            "scope": "quality-valid records",
        }
    )

    excluded_core = int(flags["exclude_from_core_survival"].sum())
    clean = working.loc[
        ~flags["exclude_from_core_survival"]
    ].copy()
    clean[EVENT_COL] = clean[EVENT_COL].astype(int)

    if clean.empty:
        fail("No valid records remain for survival analysis.")
    if int(clean[EVENT_COL].sum()) == 0:
        fail("No observed deaths remain; survival models are not estimable.")
    if int(clean[EVENT_COL].sum()) == len(clean):
        print("WARNING: no censored records remain in the core survival cohort.")

    return clean, report, excluded_core


def write_survival_flow_reports(
    source_n: int,
    quality_valid_n: int,
    quality_excluded_n: int,
    core_survival_df: pd.DataFrame,
    core_excluded_n: int,
    core_report: pd.DataFrame,
) -> None:
    """Write a unified, sequential accounting of all exclusions."""
    combined_exclusion_report = pd.concat(
        [
            pd.DataFrame(
                [
                    {
                        "criterion": "nonvalid_or_missing_quality_status",
                        "n_records": quality_excluded_n,
                        "scope": "source records",
                    }
                ]
            ),
            core_report,
        ],
        ignore_index=True,
    )
    combined_exclusion_report.to_csv(
        REPORT_DIR / "survival_exclusion_report.csv",
        index=False,
    )

    events = int(core_survival_df[EVENT_COL].sum())
    censored = int(len(core_survival_df) - events)
    pd.DataFrame(
        [
            {"step": "source_records", "n_records": source_n},
            {
                "step": "quality_valid_records",
                "n_records": quality_valid_n,
            },
            {
                "step": "excluded_nonvalid_or_missing_quality_status",
                "n_records": quality_excluded_n,
            },
            {
                "step": "excluded_for_core_survival_fields",
                "n_records": core_excluded_n,
            },
            {
                "step": "final_core_survival_records",
                "n_records": int(len(core_survival_df)),
            },
            {"step": "observed_deaths", "n_records": events},
            {"step": "right_censored", "n_records": censored},
        ]
    ).to_csv(REPORT_DIR / "survival_sample_flow.csv", index=False)


