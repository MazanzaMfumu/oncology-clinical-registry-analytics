def main() -> None:
    """Run the complete, reproducible survival-analysis workflow."""
    clean_previous_outputs()

    print(f"Project root: {PROJECT_ROOT}")
    print(f"Reading data: {DATA_FILE}")

    raw = load_dataset(DATA_FILE)
    validate_required_schema(raw)
    validate_case_ids(raw)

    quality_valid, quality_excluded_n = (
        filter_valid_quality_records(raw)
    )

    # Domain labels are checked after the explicit quality filter so that
    # records already classified as non-valid do not block the analysis.
    validate_expected_categories(
        quality_valid,
        STAGE_COL,
        STAGE_ORDER,
    )
    validate_expected_categories(
        quality_valid,
        GRADE_COL,
        EXPECTED_GRADE_VALUES,
    )
    validate_expected_categories(
        quality_valid,
        "estrogen_status",
        EXPECTED_RECEPTOR_VALUES,
    )
    validate_expected_categories(
        quality_valid,
        "progesterone_status",
        EXPECTED_RECEPTOR_VALUES,
    )

    quality_valid = validate_event_indicator(
        quality_valid
    )

    (
        survival_df,
        core_exclusion_report,
        core_excluded_n,
    ) = prepare_survival_data(quality_valid)

    write_survival_flow_reports(
        source_n=int(len(raw)),
        quality_valid_n=int(len(quality_valid)),
        quality_excluded_n=quality_excluded_n,
        core_survival_df=survival_df,
        core_excluded_n=core_excluded_n,
        core_report=core_exclusion_report,
    )

    times = selected_times_within_followup(
        survival_df
    )
    save_event_and_censor_summaries(
        survival_df
    )
    create_at_risk_table(
        survival_df,
        times,
    )
    plot_kaplan_meier(
        survival_df,
        times,
    )
    run_logrank_tests(
        survival_df
    )

    primary_df, _, _ = prepare_cox_dataset(
        survival_df,
        prefix="cox_primary",
    )
    primary, primary_warnings = fit_cox_model(
        primary_df,
        prefix="cox_primary",
        title="Primary Cox model: adjusted hazard ratios",
    )
    primary_ph = check_proportional_hazards(
        primary,
        primary_df,
        prefix="cox_primary",
    )

    sensitivity_df, _, _ = prepare_cox_dataset(
        survival_df,
        prefix="cox_stratified",
        strata_cols=SENSITIVITY_STRATA_COLS,
    )
    sensitivity, stratified_warnings = fit_cox_model(
        sensitivity_df,
        prefix="cox_stratified",
        title=(
            "Sensitivity Cox model stratified "
            "by ER and PR status"
        ),
        strata_cols=SENSITIVITY_STRATA_COLS,
    )
    stratified_ph = check_proportional_hazards(
        sensitivity,
        sensitivity_df,
        prefix="cox_stratified",
    )

    compare_cox_models(
        primary,
        sensitivity,
    )
    write_run_manifest(
        survival_df,
        primary_df,
        sensitivity_df,
        times,
    )
    automated_gate = write_commit_readiness_checklist(
        primary_ph,
        stratified_ph,
        primary_warnings,
        stratified_warnings,
    )

    print("\nAnalysis completed.")
    print("Primary model: age + overall_stage + grade")
    print(
        "Sensitivity model: same covariates, "
        "stratified by ER and PR status"
    )
    print(
        "Automated commit gate: "
        + ("PASS" if automated_gate else "FAIL")
    )
    print(
        "Manual review remains required for the new "
        "Schoenfeld and Kaplan–Meier figures."
    )
    print(f"Figures: {FIGURE_DIR}")
    print(f"Reports: {REPORT_DIR}")


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        print("\nAnalysis interrupted by the user.")
        sys.exit(130)
