def ordered_stage_values(series: pd.Series) -> list[str]:
    """Return stage labels in their configured clinical order."""
    observed = [str(value) for value in series.dropna().unique()]
    configured = [
        stage for stage in STAGE_ORDER
        if stage in observed
    ]
    remaining = sorted(
        stage for stage in observed
        if stage not in configured
    )
    return configured + remaining


def selected_times_within_followup(
    df: pd.DataFrame,
) -> list[int]:
    """Keep configured times within the observed follow-up range."""
    maximum = float(df[DURATION_COL].max())
    times = sorted(
        {
            int(time)
            for time in SELECTED_TIMES_MONTHS
            if 0 <= time <= maximum
        }
    )
    if 0 not in times:
        times.insert(0, 0)
    return times


def save_event_and_censor_summaries(
    df: pd.DataFrame,
) -> None:
    """Export overall and stage-specific event/censor counts."""
    n_total = int(len(df))
    n_events = int(df[EVENT_COL].sum())
    n_censored = n_total - n_events

    pd.DataFrame(
        [
            {
                "n_total": n_total,
                "n_events": n_events,
                "n_censored": n_censored,
                "event_percent": 100 * n_events / n_total,
                "censored_percent": 100 * n_censored / n_total,
                "minimum_followup_months": float(
                    df[DURATION_COL].min()
                ),
                "maximum_followup_months": float(
                    df[DURATION_COL].max()
                ),
            }
        ]
    ).to_csv(
        REPORT_DIR / "event_censor_summary_overall.csv",
        index=False,
    )

    by_stage = (
        df.groupby(STAGE_COL, observed=True)
        .agg(
            n_total=(EVENT_COL, "size"),
            n_events=(EVENT_COL, "sum"),
            minimum_followup_months=(DURATION_COL, "min"),
            maximum_followup_months=(DURATION_COL, "max"),
        )
        .reset_index()
    )
    by_stage["n_events"] = by_stage["n_events"].astype(int)
    by_stage["n_censored"] = (
        by_stage["n_total"] - by_stage["n_events"]
    )
    by_stage["event_percent"] = (
        100 * by_stage["n_events"] / by_stage["n_total"]
    )
    by_stage["censored_percent"] = (
        100 * by_stage["n_censored"] / by_stage["n_total"]
    )

    stage_rank = {
        stage: rank
        for rank, stage in enumerate(
            ordered_stage_values(df[STAGE_COL])
        )
    }
    by_stage["_stage_rank"] = by_stage[STAGE_COL].map(stage_rank)
    by_stage = (
        by_stage.sort_values("_stage_rank")
        .drop(columns="_stage_rank")
    )
    by_stage.to_csv(
        REPORT_DIR / "event_censor_summary_by_stage.csv",
        index=False,
    )


def create_at_risk_table(
    df: pd.DataFrame,
    times: list[int],
) -> None:
    """Export end-of-period risk counts matching the lifelines plot convention."""
    rows: list[dict[str, object]] = []

    groups: list[tuple[str, pd.DataFrame]] = [
        ("Overall", df)
    ]
    groups.extend(
        (
            stage,
            df.loc[df[STAGE_COL] == stage],
        )
        for stage in ordered_stage_values(df[STAGE_COL])
    )

    for label, group in groups:
        for time in times:
            rows.append(
                {
                    "group": label,
                    "time_months": time,
                    "n_at_risk_end_of_period": int(
                        (group[DURATION_COL] > time).sum()
                    ),
                    "cumulative_events_through_time": int(
                        (
                            (group[DURATION_COL] <= time)
                            & group[EVENT_COL].eq(1)
                        ).sum()
                    ),
                    "cumulative_censored_through_time": int(
                        (
                            (group[DURATION_COL] <= time)
                            & group[EVENT_COL].eq(0)
                        ).sum()
                    ),
                }
            )

    pd.DataFrame(rows).to_csv(
        REPORT_DIR / "at_risk_counts_selected_times.csv",
        index=False,
    )


def plot_kaplan_meier(
    df: pd.DataFrame,
    times: list[int],
) -> None:
    """Create overall and stage-specific Kaplan–Meier figures."""
    overall = KaplanMeierFitter(label="Analytical cohort")
    overall.fit(
        df[DURATION_COL],
        event_observed=df[EVENT_COL],
    )

    fig, ax = plt.subplots(figsize=(12, 8))
    overall.plot_survival_function(
        ax=ax,
        ci_show=True,
        show_censors=True,
        censor_styles={
            "marker": "|",
            "ms": 7,
            "mew": 1.2,
        },
    )
    add_at_risk_counts(
        overall,
        ax=ax,
        xticks=times,
        rows_to_show=["At risk", "Censored", "Events"],
        at_risk_count_from_start_of_period=(
            AT_RISK_COUNT_FROM_START_OF_PERIOD
        ),
    )
    ax.set_title("Overall Kaplan–Meier survival estimate")
    ax.set_xlabel("Follow-up duration (months)")
    ax.set_ylabel("Estimated survival probability")
    ax.set_ylim(0, 1.02)
    ax.grid(alpha=0.2)
    fig.subplots_adjust(bottom=0.30)
    fig.savefig(
        FIGURE_DIR
        / "overall_survival_with_censoring_and_risk_table.png",
        dpi=300,
        bbox_inches="tight",
    )
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(13, 9))
    fitters: list[KaplanMeierFitter] = []
    for stage in ordered_stage_values(df[STAGE_COL]):
        subset = df.loc[df[STAGE_COL] == stage]
        kmf = KaplanMeierFitter(label=stage)
        kmf.fit(
            subset[DURATION_COL],
            event_observed=subset[EVENT_COL],
        )
        kmf.plot_survival_function(
            ax=ax,
            ci_show=True,
            show_censors=True,
            censor_styles={
                "marker": "|",
                "ms": 5,
                "mew": 1.0,
            },
        )
        fitters.append(kmf)

    add_at_risk_counts(
        *fitters,
        ax=ax,
        xticks=times,
        rows_to_show=["At risk"],
        at_risk_count_from_start_of_period=(
            AT_RISK_COUNT_FROM_START_OF_PERIOD
        ),
    )
    ax.set_title(
        "Kaplan–Meier survival estimates by recorded stage"
    )
    ax.set_xlabel("Follow-up duration (months)")
    ax.set_ylabel("Estimated survival probability")
    ax.set_ylim(0, 1.02)
    ax.grid(alpha=0.2)
    fig.subplots_adjust(bottom=0.30)
    fig.savefig(
        FIGURE_DIR
        / "survival_by_stage_with_censoring_and_risk_table.png",
        dpi=300,
        bbox_inches="tight",
    )
    plt.close(fig)


def run_logrank_tests(df: pd.DataFrame) -> None:
    """Run global and Holm-adjusted pairwise log-rank tests."""
    global_result = multivariate_logrank_test(
        event_durations=df[DURATION_COL],
        groups=df[STAGE_COL],
        event_observed=df[EVENT_COL],
    )
    global_summary = (
        global_result.summary.reset_index(drop=True)
    )
    global_summary.insert(
        0,
        "test",
        "global_multivariate_logrank",
    )
    global_summary.insert(
        1,
        "number_of_groups",
        df[STAGE_COL].nunique(),
    )
    global_summary.to_csv(
        REPORT_DIR / "logrank_global.csv",
        index=False,
    )

    pairwise = pairwise_logrank_test(
        event_durations=df[DURATION_COL],
        groups=df[STAGE_COL],
        event_observed=df[EVENT_COL],
    ).summary.reset_index()

    first_two = pairwise.columns[:2].tolist()
    pairwise = pairwise.rename(
        columns={
            first_two[0]: "group_1",
            first_two[1]: "group_2",
        }
    )
    reject, adjusted, _, _ = multipletests(
        pairwise["p"].to_numpy(),
        alpha=0.05,
        method="holm",
    )
    pairwise["p_holm"] = adjusted
    pairwise["reject_h0_after_holm"] = reject
    pairwise.to_csv(
        REPORT_DIR / "logrank_pairwise_holm.csv",
        index=False,
    )


