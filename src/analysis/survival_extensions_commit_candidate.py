def validate_case_ids(df: pd.DataFrame) -> None:
    """Require non-missing and unique technical case identifiers."""
    series = df[CASE_ID_COL].astype("string").str.strip()
    n_missing = int(series.isna().sum() + series.eq("").sum())
    n_duplicated = int(series[series.notna() & series.ne("")].duplicated().sum())

    pd.DataFrame(
        [
            {"metric": "n_records", "value": int(len(df))},
            {"metric": "missing_or_blank_case_id", "value": n_missing},
            {"metric": "duplicated_case_id", "value": n_duplicated},
        ]
    ).to_csv(REPORT_DIR / "case_id_validation.csv", index=False)

    if n_missing:
        fail(f"{n_missing} record(s) have a missing or blank {CASE_ID_COL!r}.")
    if n_duplicated:
        fail(f"{n_duplicated} duplicated {CASE_ID_COL!r} value(s) were detected.")


def normalize_text(series: pd.Series) -> pd.Series:
    """Trim categorical labels while preserving missing values."""
    return series.astype("string").str.strip()


def validate_expected_categories(
    df: pd.DataFrame,
    column: str,
    expected_values: list[str],
) -> None:
    """Stop on unexpected non-missing category labels."""
    observed = sorted(str(value) for value in normalize_text(df[column]).dropna().unique())
    unexpected = sorted(set(observed).difference(expected_values))
    if unexpected:
        fail(
            f"Unexpected categories in {column!r}: {unexpected}.\n"
            f"Expected categories: {expected_values}"
        )


