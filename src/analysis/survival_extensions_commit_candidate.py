def load_dataset(path: Path) -> pd.DataFrame:
    """Load the processed CSV used by this project."""
    if not path.exists():
        fail(
            f"Data file not found: {path}\n"
            "Expected: data/processed/oncology_registry_validated.csv"
        )
    if path.suffix.lower() != ".csv":
        fail("This project configuration expects a CSV file.")
    try:
        return pd.read_csv(path, encoding="utf-8")
    except Exception as exc:
        fail(f"Could not read the CSV: {type(exc).__name__}: {exc}")
    return pd.DataFrame()  # Unreachable.


