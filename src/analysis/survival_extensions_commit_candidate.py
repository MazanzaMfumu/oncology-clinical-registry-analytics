def apply_reference_categories(
    df: pd.DataFrame,
    categorical_cols: list[str],
) -> pd.DataFrame:
    """Apply every categorical reference explicitly before dummy encoding."""
    result = df.copy()

    missing_references = [
        column
        for column in categorical_cols
        if column not in REFERENCE_CATEGORIES
    ]
    if missing_references:
        fail(
            "Explicit reference categories are missing for: "
            f"{missing_references}"
        )

    for column in categorical_cols:
        result[column] = normalize_text(result[column])
        reference = REFERENCE_CATEGORIES[column]
        observed = sorted(
            str(value)
            for value in result[column].dropna().unique()
        )
        if reference not in observed:
            fail(
                f"Reference category {reference!r} was not found "
                f"in {column!r}. Observed categories: {observed}"
            )
        categories = [
            reference,
            *[
                value
                for value in observed
                if value != reference
            ],
        ]
        result[column] = pd.Categorical(
            result[column],
            categories=categories,
        )

    return result


def export_level_diagnostics(
    complete_raw: pd.DataFrame,
    variables: list[str],
    prefix: str,
    strata_cols: list[str] | None = None,
) -> pd.DataFrame:
    """Export counts, events, censoring, and sparse-cell warnings by level."""
    strata_cols = strata_cols or []
    rows: list[dict[str, object]] = []

    for variable in variables:
        for level, group in complete_raw.groupby(
            variable,
            observed=True,
            dropna=False,
        ):
            n_total = int(len(group))
            n_events = int(group[EVENT_COL].sum())
            rows.append(
                {
                    "variable": variable,
                    "level": str(level),
                    "role": (
                        "stratum"
                        if variable in strata_cols
                        else "covariate"
                    ),
                    "is_reference": bool(
                        variable in REFERENCE_CATEGORIES
                        and str(level)
                        == REFERENCE_CATEGORIES[variable]
                    ),
                    "n_total": n_total,
                    "n_events": n_events,
                    "n_censored": n_total - n_events,
                    "event_percent": (
                        100 * n_events / n_total
                        if n_total
                        else np.nan
                    ),
                    "sparse_n_warning": (
                        n_total
                        < MIN_RECOMMENDED_GROUP_SIZE
                    ),
                    "sparse_event_warning": (
                        n_events
                        < MIN_RECOMMENDED_EVENTS
                    ),
                }
            )

    diagnostics = pd.DataFrame(rows)
    diagnostics.to_csv(
        REPORT_DIR
        / f"{prefix}_categorical_level_diagnostics.csv",
        index=False,
    )
    return diagnostics


def export_combined_strata_diagnostics(
    complete_raw: pd.DataFrame,
    strata_cols: list[str],
    prefix: str,
) -> pd.DataFrame:
    """Report the actual combined strata used by the stratified Cox model."""
    if not strata_cols:
        return pd.DataFrame()

    combined = (
        complete_raw.groupby(
            strata_cols,
            observed=True,
            dropna=False,
        )
        .agg(
            n_total=(EVENT_COL, "size"),
            n_events=(EVENT_COL, "sum"),
        )
        .reset_index()
    )
    combined["n_events"] = combined["n_events"].astype(int)
    combined["n_censored"] = (
        combined["n_total"] - combined["n_events"]
    )
    combined["event_percent"] = (
        100 * combined["n_events"] / combined["n_total"]
    )
    combined["sparse_n_warning"] = (
        combined["n_total"] < MIN_RECOMMENDED_GROUP_SIZE
    )
    combined["sparse_event_warning"] = (
        combined["n_events"] < MIN_RECOMMENDED_EVENTS
    )
    combined["zero_event_blocker"] = combined["n_events"].eq(0)

    combined.to_csv(
        REPORT_DIR
        / f"{prefix}_combined_strata_diagnostics.csv",
        index=False,
    )

    if combined["zero_event_blocker"].any():
        problematic = combined.loc[
            combined["zero_event_blocker"],
            strata_cols,
        ].to_dict(orient="records")
        fail(
            "At least one ER/PR stratum has zero observed deaths: "
            f"{problematic}. The stratified sensitivity model is not "
            "adequately supported without further methodological review."
        )

    return combined


def prepare_cox_dataset(
    df: pd.DataFrame,
    prefix: str,
    strata_cols: list[str] | None = None,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Create a complete-case, reference-controlled Cox dataset."""
    strata_cols = strata_cols or []

    configured_columns = (
        COX_NUMERIC_COLS
        + COX_CATEGORICAL_COLS
        + strata_cols
    )
    duplicates = sorted(
        {
            column
            for column in configured_columns
            if configured_columns.count(column) > 1
        }
    )
    if duplicates:
        fail(
            f"Columns configured more than once in {prefix}: "
            f"{duplicates}"
        )

    all_columns = [
        DURATION_COL,
        EVENT_COL,
        *configured_columns,
    ]
    missing = [
        column
        for column in all_columns
        if column not in df.columns
    ]
    if missing:
        fail(
            f"Configured Cox columns are missing: {missing}.\n"
            f"Available columns:\n{show_available_columns(df)}"
        )

    raw = df[all_columns].copy()
    raw[DURATION_COL] = pd.to_numeric(
        raw[DURATION_COL],
        errors="coerce",
    )
    raw[EVENT_COL] = pd.to_numeric(
        raw[EVENT_COL],
        errors="coerce",
    )

    for column in COX_NUMERIC_COLS:
        raw[column] = pd.to_numeric(
            raw[column],
            errors="coerce",
        )

    raw = apply_reference_categories(
        raw,
        COX_CATEGORICAL_COLS,
    )

    for column in strata_cols:
        raw[column] = normalize_text(raw[column])

    missingness = (
        raw.isna()
        .sum()
        .rename("n_missing")
        .reset_index()
        .rename(columns={"index": "column"})
    )
    missingness.to_csv(
        REPORT_DIR / f"{prefix}_missingness_by_column.csv",
        index=False,
    )

    before = int(len(raw))
    complete_raw = raw.dropna().copy()
    after = int(len(complete_raw))
    if complete_raw.empty:
        fail(f"No complete cases remain for {prefix}.")

    # Use ordinary Python strings for strata labels after missingness removal.
    for column in strata_cols:
        complete_raw[column] = complete_raw[column].astype(str)

    level_diagnostics = export_level_diagnostics(
        complete_raw,
        [
            *COX_CATEGORICAL_COLS,
            *strata_cols,
        ],
        prefix,
        strata_cols,
    )
    export_combined_strata_diagnostics(
        complete_raw,
        strata_cols,
        prefix,
    )

    encoded = pd.get_dummies(
        complete_raw,
        columns=COX_CATEGORICAL_COLS,
        drop_first=True,
        dtype=int,
    )

    covariate_columns = [
        column
        for column in encoded.columns
        if column not in {
            DURATION_COL,
            EVENT_COL,
            *strata_cols,
        }
    ]
    constants = [
        column
        for column in covariate_columns
        if encoded[column].nunique() <= 1
    ]
    if constants:
        fail(
            f"Constant covariates in {prefix}: {constants}"
        )

    n_events = int(encoded[EVENT_COL].sum())
    n_parameters = int(len(covariate_columns))
    if n_events == 0:
        fail(f"No events remain in the complete-case sample for {prefix}.")
    if n_parameters == 0:
        fail(f"No estimable parameters remain for {prefix}.")

    events_per_parameter = n_events / n_parameters
    sample_flow = pd.DataFrame(
        [
            {
                "metric": "core_survival_records",
                "value": before,
            },
            {
                "metric": "cox_complete_cases",
                "value": after,
            },
            {
                "metric": "cox_records_excluded_for_missingness",
                "value": before - after,
            },
            {
                "metric": "cox_observed_events",
                "value": n_events,
            },
            {
                "metric": "cox_estimated_parameters",
                "value": n_parameters,
            },
            {
                "metric": "events_per_estimated_parameter_descriptive",
                "value": events_per_parameter,
            },
            {
                "metric": "events_per_parameter_warning_below",
                "value": MIN_EVENTS_PER_PARAMETER_WARNING,
            },
            {
                "metric": "events_per_parameter_warning",
                "value": (
                    events_per_parameter
                    < MIN_EVENTS_PER_PARAMETER_WARNING
                ),
            },
        ]
    )
    sample_flow.to_csv(
        REPORT_DIR / f"{prefix}_sample_flow.csv",
        index=False,
    )

    pd.DataFrame(
        [
            {
                "variable": variable,
                "reference_category": reference,
            }
            for variable, reference
            in REFERENCE_CATEGORIES.items()
            if variable in COX_CATEGORICAL_COLS
        ]
    ).to_csv(
        REPORT_DIR / f"{prefix}_reference_categories.csv",
        index=False,
    )

    return encoded, level_diagnostics, sample_flow


def fit_cox_model(
    cox_df: pd.DataFrame,
    prefix: str,
    title: str,
    strata_cols: list[str] | None = None,
) -> tuple[CoxPHFitter, pd.DataFrame]:
    """Fit Cox model, capture warnings, and reject unstable numerical output."""
    strata_cols = strata_cols or []
    cph = CoxPHFitter(penalizer=COX_PENALIZER)

    caught_warnings: list[warnings.WarningMessage]
    try:
        with warnings.catch_warnings(record=True) as caught:
            warnings.simplefilter("always")
            cph.fit(
                cox_df,
                duration_col=DURATION_COL,
                event_col=EVENT_COL,
                strata=strata_cols or None,
                show_progress=False,
            )
        caught_warnings = list(caught)
    except Exception as exc:
        fail(
            f"{prefix} did not converge or could not be fitted.\n"
            f"{type(exc).__name__}: {exc}\n"
            "Review sparse categories, correlated variables, and coding."
        )

    warning_rows = [
        {
            "category": item.category.__name__,
            "message": str(item.message),
        }
        for item in caught_warnings
    ]
    warnings_df = pd.DataFrame(
        warning_rows,
        columns=["category", "message"],
    )
    warnings_df.to_csv(
        REPORT_DIR / f"{prefix}_fit_warnings.csv",
        index=False,
    )

    convergence_warning_messages = [
        str(item.message)
        for item in caught_warnings
        if issubclass(item.category, ConvergenceWarning)
    ]
    if convergence_warning_messages:
        fail(
            f"{prefix} emitted ConvergenceWarning:\n- "
            + "\n- ".join(convergence_warning_messages)
        )

    summary = (
        cph.summary.reset_index()
        .rename(columns={cph.summary.index.name or "index": "term"})
    )
    if "term" not in summary.columns:
        summary = summary.rename(
            columns={summary.columns[0]: "term"}
        )

    numeric_columns_to_check = [
        column
        for column in [
            "coef",
            "exp(coef)",
            "se(coef)",
            "coef lower 95%",
            "coef upper 95%",
            "exp(coef) lower 95%",
            "exp(coef) upper 95%",
            "p",
        ]
        if column in summary.columns
    ]
    finite_values = np.isfinite(
        summary[numeric_columns_to_check]
        .to_numpy(dtype=float)
    ).all()
    if not finite_values:
        fail(
            f"{prefix} produced non-finite coefficients, standard errors, "
            "confidence limits, or p-values."
        )

    summary.to_csv(
        REPORT_DIR / f"{prefix}_model_summary.csv",
        index=False,
    )

    with (
        REPORT_DIR / f"{prefix}_model_console_summary.txt"
    ).open("w", encoding="utf-8") as handle:
        with redirect_stdout(handle):
            cph.print_summary(decimals=4)

    pd.DataFrame(
        [
            {
                "metric": "concordance_index",
                "value": cph.concordance_index_,
            },
            {
                "metric": "log_likelihood",
                "value": cph.log_likelihood_,
            },
            {
                "metric": "partial_AIC",
                "value": cph.AIC_partial_,
            },
            {
                "metric": "n_observations",
                "value": int(len(cox_df)),
            },
            {
                "metric": "n_events",
                "value": int(cox_df[EVENT_COL].sum()),
            },
            {
                "metric": "strata",
                "value": json_text(strata_cols),
            },
            {
                "metric": "convergence_warning_count",
                "value": len(convergence_warning_messages),
            },
        ]
    ).to_csv(
        REPORT_DIR / f"{prefix}_model_metrics.csv",
        index=False,
    )

    fig, ax = plt.subplots(
        figsize=(
            10,
            max(5, 0.55 * len(summary) + 2),
        )
    )
    cph.plot(ax=ax, hazard_ratios=True)
    ax.set_title(title)
    ax.set_xlabel(
        "Hazard ratio with 95% confidence interval"
    )
    ax.axvline(1.0, linestyle="--", linewidth=1)
    fig.tight_layout()
    fig.savefig(
        FIGURE_DIR
        / f"{prefix}_adjusted_hazard_ratios.png",
        dpi=300,
        bbox_inches="tight",
    )
    plt.close(fig)

    return cph, warnings_df


def check_proportional_hazards(
    cph: CoxPHFitter,
    cox_df: pd.DataFrame,
    prefix: str,
) -> pd.DataFrame:
    """Export Holm-adjusted PH tests, text advice, and Schoenfeld plots."""
    try:
        result = proportional_hazard_test(
            cph,
            cox_df,
            time_transform="rank",
        )
    except Exception as exc:
        fail(
            f"Could not run the PH test for {prefix}: "
            f"{type(exc).__name__}: {exc}"
        )

    summary = (
        result.summary.reset_index()
        .rename(columns={result.summary.index.name or "index": "term"})
    )
    if "term" not in summary.columns:
        summary = summary.rename(
            columns={summary.columns[0]: "term"}
        )

    reject, adjusted, _, _ = multipletests(
        summary["p"].to_numpy(),
        alpha=0.05,
        method="holm",
    )
    summary["p_holm"] = adjusted
    summary["reject_ph_after_holm"] = reject
    summary.to_csv(
        REPORT_DIR
        / f"{prefix}_proportional_hazards_test.csv",
        index=False,
    )

    plt.close("all")
    report_path = (
        REPORT_DIR
        / f"{prefix}_check_assumptions_report.txt"
    )
    try:
        with report_path.open(
            "w",
            encoding="utf-8",
        ) as handle:
            with redirect_stdout(handle):
                cph.check_assumptions(
                    cox_df,
                    p_value_threshold=0.05,
                    show_plots=True,
                )
    except Exception as exc:
        plt.close("all")
        fail(
            f"Could not run check_assumptions for {prefix}: "
            f"{type(exc).__name__}: {exc}"
        )

    figure_index_rows: list[dict[str, object]] = []
    for position, number in enumerate(
        plt.get_fignums(),
        start=1,
    ):
        figure = plt.figure(number)
        title = ""
        if figure._suptitle is not None:
            title = figure._suptitle.get_text()
        if not title and figure.axes:
            title = figure.axes[0].get_title()
        filename = (
            f"{prefix}_schoenfeld_diagnostic_"
            f"{position:02d}_{sanitize_filename(title)}.png"
        )
        figure.savefig(
            FIGURE_DIR / filename,
            dpi=300,
            bbox_inches="tight",
        )
        figure_index_rows.append(
            {
                "position": position,
                "filename": filename,
                "figure_title": title,
            }
        )
    plt.close("all")

    pd.DataFrame(
        figure_index_rows,
        columns=[
            "position",
            "filename",
            "figure_title",
        ],
    ).to_csv(
        REPORT_DIR
        / f"{prefix}_schoenfeld_figure_index.csv",
        index=False,
    )

    return summary


def compare_cox_models(
    primary: CoxPHFitter,
    sensitivity: CoxPHFitter,
) -> None:
    """Compare common hazard-ratio estimates across both models."""
    left = primary.summary.reset_index()
    left = left.rename(
        columns={
            left.columns[0]: "term",
            "exp(coef)": "primary_hr",
            "exp(coef) lower 95%": "primary_hr_lower_95",
            "exp(coef) upper 95%": "primary_hr_upper_95",
        }
    )
    right = sensitivity.summary.reset_index()
    right = right.rename(
        columns={
            right.columns[0]: "term",
            "exp(coef)": "stratified_hr",
            "exp(coef) lower 95%": "stratified_hr_lower_95",
            "exp(coef) upper 95%": "stratified_hr_upper_95",
        }
    )

    left = left[
        [
            "term",
            "primary_hr",
            "primary_hr_lower_95",
            "primary_hr_upper_95",
        ]
    ]
    right = right[
        [
            "term",
            "stratified_hr",
            "stratified_hr_lower_95",
            "stratified_hr_upper_95",
        ]
    ]

    comparison = left.merge(
        right,
        on="term",
        how="outer",
        validate="one_to_one",
    )
    comparison["relative_hr_change_percent"] = (
        100
        * (
            comparison["stratified_hr"]
            - comparison["primary_hr"]
        )
        / comparison["primary_hr"]
    )
    comparison.to_csv(
        REPORT_DIR
        / "cox_primary_vs_stratified_sensitivity.csv",
        index=False,
    )


