def fail(message: str) -> None:
    """Stop with a readable error and a non-zero exit status."""
    raise SystemExit(f"\nERROR: {message}\n")


def show_available_columns(df: pd.DataFrame) -> str:
    """Return available columns in a readable form."""
    return "\n".join(f"  - {column}" for column in df.columns)


def sha256_file(path: Path) -> str:
    """Calculate a SHA-256 digest without loading the whole file into memory."""
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def project_relative_path(path: Path) -> str:
    """Return a portable project-relative path, never a local absolute path."""
    try:
        return path.resolve().relative_to(PROJECT_ROOT.resolve()).as_posix()
    except ValueError:
        return path.name


def json_text(value: object) -> str:
    """Serialize lists and dictionaries in a portable, unambiguous format."""
    return json.dumps(value, ensure_ascii=False, sort_keys=True)


def sanitize_filename(text: str, maximum_length: int = 90) -> str:
    """Create a safe filename fragment from a figure title."""
    cleaned = re.sub(r"[^A-Za-z0-9._-]+", "_", text.strip())
    cleaned = cleaned.strip("._-")
    return (cleaned[:maximum_length] or "diagnostic").lower()


